// Renders the share image and the placeholder icons from HTML templates that use the site's tokens,
// fonts and real companion art, so no colour value has to be typed anywhere outside tokens.css.
// Usage: node scripts/brand-assets.mjs
// Writes: public/og.png (1200x630), public/favicon.svg, public/favicon-32.png, public/apple-touch-icon.png

import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright-core";

const tpl = (name) => pathToFileURL(resolve("scripts/assets", name)).href;
const out = (name) => resolve("public", name);
const browser = await chromium.launch({ channel: "chrome" });

try {
  // Share image.
  const og = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  await og.goto(tpl("og.html"), { waitUntil: "load" });
  await og.evaluate(() => document.fonts.ready);
  const fonts = await og.evaluate(() => [...document.fonts].filter((f) => f.status === "loaded").map((f) => f.family.replace(/"/g, "")));
  for (const need of ["DM Sans", "Fraunces", "Syne"]) if (!fonts.includes(need)) throw new Error(`og.png: font not loaded: ${need}`);
  await og.screenshot({ path: out("og.png"), type: "png" });
  await og.close();

  // Icons: rasterised PNGs, plus an SVG with the token colours resolved into it.
  for (const [file, size] of [["favicon-32.png", 32], ["apple-touch-icon.png", 180]]) {
    const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
    await page.goto(tpl("icon.html") + (file.startsWith("apple") ? "?square" : ""), { waitUntil: "load" });
    await page.screenshot({ path: out(file), type: "png", omitBackground: !file.startsWith("apple") });
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 64, height: 64 } });
  await page.goto(tpl("icon.html"), { waitUntil: "load" });
  const svg = await page.evaluate(() => {
    const src = document.getElementById("icon");
    const copy = src.cloneNode(true);
    const real = [...src.querySelectorAll("*")];
    [...copy.querySelectorAll("*")].forEach((el, i) => {
      const cs = getComputedStyle(real[i]);
      if (cs.fill && cs.fill !== "none") el.setAttribute("fill", cs.fill); else el.setAttribute("fill", "none");
      if (cs.stroke && cs.stroke !== "none") {
        el.setAttribute("stroke", cs.stroke);
        el.setAttribute("stroke-width", cs.strokeWidth.replace("px", ""));
        el.setAttribute("stroke-linecap", cs.strokeLinecap);
      }
      el.removeAttribute("class");
    });
    copy.removeAttribute("id");
    return copy.outerHTML;
  });
  await writeFile(out("favicon.svg"), `<!-- PLACEHOLDER until the logo file is in the repo. Generated by scripts/brand-assets.mjs. -->\n${svg}\n`);
  await page.close();
} finally {
  await browser.close();
}
console.log("Wrote public/og.png, public/favicon.svg, public/favicon-32.png, public/apple-touch-icon.png");
